import { HistoryUnavailable } from "@/components/HistoryUnavailable";
import { RegenerateButton } from "@/components/RegenerateButton";
import { Shell } from "@/components/Shell";
import { requireAdminPage } from "@/lib/admin.server";
import {
  listConceptContentForTeacher,
  type TeacherConceptRow,
  type TeacherSlot,
  type TeacherVersion,
} from "@/lib/db/queries/concepts.server";
import { load } from "@/lib/db/queries/history.server";
import { formatWhen } from "@/lib/format";

// Per request: the content and its review state change as the pipeline runs.
export const dynamic = "force-dynamic";

/**
 * Teacher review of the shared concept content (spec 002 FR-051 to FR-055). Shows what students
 * see (the live version), the replacement waiting behind it and why it was held back, who made
 * and approved each, and lets a teacher ask for a new one. It reads concept content only: no
 * student data of any kind.
 */
export default async function AdminConceptsPage() {
  await requireAdminPage();
  const loaded = await load(listConceptContentForTeacher);

  return (
    <Shell backHref="/">
      <h1 className="page-h1" style={{ fontSize: 24, margin: "4px 0 6px" }}>
        Concept content
      </h1>
      <p className="page-sub" style={{ marginBottom: 16 }}>
        The live version is what students see. A replacement is shown to no one until it passes review.
      </p>
      {loaded.status === "unavailable" ? (
        <HistoryUnavailable />
      ) : loaded.data.length === 0 ? (
        <p className="page-sub">No unit has adopted concepts yet.</p>
      ) : (
        byUnit(loaded.data).map(([unitTitle, rows]) => (
          <section key={unitTitle} style={{ marginBottom: 24 }}>
            <h2 className="eyebrow" style={{ margin: "0 0 8px" }}>
              {unitTitle}
            </h2>
            {rows.map((row) => (
              <ConceptCard key={row.conceptId} row={row} />
            ))}
          </section>
        ))
      )}
    </Shell>
  );
}

function byUnit(rows: TeacherConceptRow[]): Array<[string, TeacherConceptRow[]]> {
  const groups = new Map<string, TeacherConceptRow[]>();
  for (const row of rows) groups.set(row.unitTitle, [...(groups.get(row.unitTitle) ?? []), row]);
  return [...groups.entries()];
}

function ConceptCard({ row }: { row: TeacherConceptRow }) {
  return (
    <div className="rd-card admin-concept">
      <div className="admin-concept-title">{row.description}</div>
      <div className="admin-concept-id">{row.conceptId}</div>
      <Item row={row} kind="summary" slot={row.summary} />
      <Item row={row} kind="illustration" slot={row.illustration} />
    </div>
  );
}

function Item({ row, kind, slot }: { row: TeacherConceptRow; kind: "summary" | "illustration"; slot: TeacherSlot | null }) {
  return (
    <div className="admin-item">
      <div className="admin-item-head">
        <strong>{kind === "summary" ? "Summary" : "Picture"}</strong>
        <RegenerateButton conceptId={row.conceptId} kind={kind} />
      </div>
      {!slot || (!slot.live && !slot.replacement) ? (
        <p className="admin-none">Not generated.</p>
      ) : (
        <>
          <Version label="Live (students see this)" conceptId={row.conceptId} version={slot.live} kind={kind} />
          <Version label="Replacement (no student sees this)" conceptId={row.conceptId} version={slot.replacement} kind={kind} />
        </>
      )}
      {slot?.lastError && (
        <p className="admin-error">
          Last error{slot.lastErrorAt ? ` (${formatWhen(slot.lastErrorAt)})` : ""}: {slot.lastError}
        </p>
      )}
    </div>
  );
}

function Version({
  label,
  conceptId,
  version,
  kind,
}: {
  label: string;
  conceptId: string;
  version: TeacherVersion | null;
  kind: "summary" | "illustration";
}) {
  if (!version) return null;
  return (
    <div className="admin-version">
      <div className="eyebrow">
        {label} <span className={`rd-pill${version.status === "approved" ? "" : " warn"}`}>{version.status.replace("_", " ")}</span>
      </div>
      {kind === "summary" && version.bullets && (
        <ul>
          {version.bullets.map((b, i) => (
            <li key={i}>{b}</li>
          ))}
        </ul>
      )}
      {kind === "summary" && version.brief && <p className="admin-meta">Picture wanted: {version.brief}</p>}
      {kind === "illustration" && version.hasSvg && (
        // eslint-disable-next-line @next/next/no-img-element -- an SVG shown only through <img>, never inlined
        <img
          className="concept-illustration"
          src={`/api/admin/concepts/${conceptId}/illustration?v=${version.id}`}
          alt={version.alt ?? ""}
        />
      )}
      {version.reviewerReason && <p className="admin-reason">Reviewer: {version.reviewerReason}</p>}
      <p className="admin-meta">
        Generated by {version.generatorModel} on {formatWhen(version.generatedAt)}
        {version.origin === "teacher" ? " (teacher request)" : version.attemptNo === 2 ? " (automatic retry)" : ""}.{" "}
        {version.reviewedAt
          ? `Reviewed by ${version.reviewerModel ?? "unknown"} on ${formatWhen(version.reviewedAt)}.`
          : "Not reviewed yet."}{" "}
        {version.approvedBy ? `Approved by ${version.approvedBy}.` : ""}
      </p>
    </div>
  );
}
