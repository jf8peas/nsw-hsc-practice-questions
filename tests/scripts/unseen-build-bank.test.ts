// The unseen-text bank generator's pure half (spec 008, research R2): deterministic output, texts
// stored once, the median fallback for uncounted answer lines, the descriptions kept out of the public
// files, and the refusals.

import { describe, expect, it } from "vitest";

import { buildFiles, withoutPending, type BankFile } from "../../scripts/unseen-build-bank-lib";

const UNIT = "y12-english-advanced-unseen-texts";

const bank = (): BankFile => ({
  paper: { school: "Invented High School", short: "Invented", year: 2026, exam: "Trial" },
  texts: [
    {
      id: "inv26-t1", form: "poem", heading: "Text 1 – Poem", title: "Platform", author: "A. Invented",
      sourceLine: "From a collection, 2020", body: { kind: "poem", stanzas: [["one", "two"], ["three"]], lineNumbers: { every: 5 } },
      footnotes: [{ mark: "*", text: "tide: the sea" }], hscChecked: "2026-11-19",
    },
    {
      id: "inv26-t2", form: "visual", heading: "Text 2 – Image", title: "Table", author: "B. Artist",
      sourceLine: "Illustration, 2021", body: { kind: "image", image: "inv26-t2", alt: "A black and white drawing of a crowded table" },
      hscChecked: "2026-11-19", description: "A round table seen from above, crowded with plates.",
    },
  ],
  questions: [
    {
      slug: "inv26-q1", qNo: 1, maxMarks: 3, verb: "analyse", prompt: "Analyse how the poet explores waiting.", answerLines: 17,
      skills: ["technique-effect", "human-experience"], outcome: "EAV-12-01", textId: "inv26-t1",
      key: { criteria: "3 – Effective.\n2 – Sound.\n1 – Limited.", notes: "None provided by the school.", model: "A model answer.", modelOrigin: "school", criteriaOrigin: "school" },
    },
    {
      slug: "inv26-q2", qNo: 2, maxMarks: 4, verb: "explain", prompt: "Explain the image.", answerLines: null,
      skills: ["apt-evidence"], outcome: "EAV-12-02", textId: "inv26-t2",
      key: { criteria: "4 – a\n3 – b\n2 – c\n1 – d", notes: "n", model: "Another model.", modelOrigin: "drafted", criteriaOrigin: "drafted", reviewedOn: "2026-11-19" },
    },
  ],
});

describe("buildFiles", () => {
  it("writes the four files with a generated header", () => {
    const files = buildFiles([bank()]);
    expect(Object.keys(files)).toEqual(["texts.ts", "questions.ts", "keys.ts", "descriptions.ts"]);
    for (const f of Object.values(files)) expect(f).toContain("GENERATED by scripts/unseen-build-bank.ts");
  });

  it("is deterministic: a second run gives identical output", () => {
    expect(buildFiles([bank()])).toEqual(buildFiles([bank()]));
  });

  it("builds the public question with the credit, the tag concept ids and lines × 12 words", () => {
    const { "questions.ts": q } = buildFiles([bank()]);
    expect(q).toContain(`"id": "${UNIT}.inv26-q1"`);
    expect(q).toContain('"source": "Invented 2026 Trial, Q1"');
    expect(q).toContain('"suggestedWords": 204');
    expect(q).toContain('"suggestedFrom": "lines"');
    expect(q).toContain(`"${UNIT}.c-technique-effect"`);
  });

  it("falls back to the median for the mark value when the answer lines cannot be counted", () => {
    const { "questions.ts": q } = buildFiles([bank()]);
    expect(q).toContain('"suggestedWords": 276');
    expect(q).toContain('"suggestedFrom": "median"');
  });

  it("keeps the key and the visual description out of the public files", () => {
    const files = buildFiles([bank()]);
    for (const name of ["texts.ts", "questions.ts"] as const) {
      expect(files[name]).not.toContain("A model answer.");
      expect(files[name]).not.toContain("Effective.");
      expect(files[name]).not.toContain("crowded with plates");
      expect(files[name]).not.toContain("SERVER ONLY: never import");
    }
    expect(files["keys.ts"]).toContain("SERVER ONLY: never import");
    expect(files["keys.ts"]).toContain("A model answer.");
    expect(files["descriptions.ts"]).toContain("crowded with plates");
    expect(files["descriptions.ts"]).toContain("SERVER ONLY: never import");
  });

  it("stores a text once even when two questions point at it", () => {
    const b = bank();
    b.questions.push({ ...b.questions[0], slug: "inv26-q3", qNo: 3 });
    const { "texts.ts": t, "questions.ts": q } = buildFiles([b]);
    expect(t.match(/"id": "inv26-t1"/g)).toHaveLength(1);
    expect(q.match(/"textId": "inv26-t1"/g)).toHaveLength(2);
  });

  it("refuses a text with no hscChecked date, a duplicate id, a missing text, an unknown skill and a visual with no description", () => {
    const noCheck = bank();
    noCheck.texts[0].hscChecked = "";
    expect(() => buildFiles([noCheck])).toThrow(/no hscChecked/);

    const dup = bank();
    dup.questions[1].slug = "inv26-q1";
    expect(() => buildFiles([dup])).toThrow(/duplicate question slug/);

    const missing = bank();
    missing.questions[0].textId = "nope";
    expect(() => buildFiles([missing])).toThrow(/text nope not found/);

    const skill = bank();
    (skill.questions[0].skills as string[]).push("vibes");
    expect(() => buildFiles([skill])).toThrow(/unknown skill vibes/);

    const noDesc = bank();
    noDesc.texts[1].description = " ";
    expect(() => buildFiles([noDesc])).toThrow(/no description for the marker/);
  });
});

describe("withoutPending", () => {
  it("keeps unreviewed drafted questions, and the texts only they use, out of the unit", () => {
    const b = bank();
    b.questions[1].key.reviewedOn = undefined;
    const { banks, pending } = withoutPending([b]);
    expect(pending).toEqual(["inv26-q2"]);
    expect(banks[0].questions.map((q) => q.slug)).toEqual(["inv26-q1"]);
    expect(banks[0].texts.map((t) => t.id)).toEqual(["inv26-t1"]);
  });

  it("keeps a drafted question once it has a reviewedOn date, and school material always", () => {
    const { banks, pending } = withoutPending([bank()]);
    expect(pending).toEqual([]);
    expect(banks[0].questions).toHaveLength(2);
  });

  it("drops a bank file whose questions are all pending", () => {
    const b = bank();
    b.questions = [b.questions[1]];
    b.questions[0].key.reviewedOn = undefined;
    expect(withoutPending([b]).banks).toEqual([]);
  });
});
