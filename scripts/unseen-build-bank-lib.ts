// The pure half of the unseen-text bank generator (spec 008, research R2): turns the content task's
// bank files (resources/english-unseen/bank/*.json, gitignored, verbatim paper material) into the
// unit's TypeScript, deterministically, so the 37-paper extraction becomes reviewable committed code.
// No file or network access here; scripts/unseen-build-bank.ts reads and writes.

import { MEDIAN_WORDS } from "../lib/unseen/limits";
import { SKILL_IDS, skillConceptId, type SkillId } from "../lib/unseen/skills";
import { sourceOf } from "../lib/unseen/source";
import type { UnseenPaper, UnseenText } from "../lib/types";

export const UNIT_ID = "y12-english-advanced-unseen-texts";

/** One bank file: one paper, its texts (each once) and the kept questions that point at them. */
export interface BankFile {
  paper: Omit<UnseenPaper, "qNo">;
  texts: Array<UnseenText & { /** visual texts only: the marker's written description (key) */ description?: string }>;
  questions: BankQuestion[];
}

export interface BankQuestion {
  /** The id suffix, e.g. "fs25-q1" (equal to the pilot's case-id prefix). */
  slug: string;
  qNo: 1 | 2 | 3 | 4;
  maxMarks: number;
  verb: string;
  prompt: string;
  parts?: Array<{ label: string; text: string; marks: number }>;
  /** Every answer line the paper gives (main space plus additional space); null when it cannot be counted. */
  answerLines: number | null;
  skills: SkillId[];
  outcome: "EAV-12-01" | "EAV-12-02" | "EAV-12-04";
  textId: string;
  key: {
    criteria: string;
    notes: string;
    model: string;
    modelOrigin: "school" | "drafted";
    criteriaOrigin: "school" | "drafted";
    reviewedOn?: string;
  };
}


/**
 * A question whose criteria or model answer was drafted or generated and has no `reviewedOn` date is
 * pending review (FR-042): content validation refuses to ship it, so by default the generator keeps it
 * out of the unit (it stays in the bank file and in the review report) until a teacher has approved it.
 */
export const isPending = (q: BankQuestion): boolean =>
  (q.key.modelOrigin === "drafted" || q.key.criteriaOrigin === "drafted") && !q.key.reviewedOn;

/** The bank files without their pending questions, and without texts only a pending question used. */
export function withoutPending(banks: BankFile[]): { banks: BankFile[]; pending: string[] } {
  const pending: string[] = [];
  const kept: BankFile[] = [];
  for (const bank of banks) {
    const questions = bank.questions.filter((q) => {
      if (isPending(q)) pending.push(q.slug);
      return !isPending(q);
    });
    if (questions.length === 0) continue;
    const used = new Set(questions.map((q) => q.textId));
    kept.push({ ...bank, texts: bank.texts.filter((t) => used.has(t.id)), questions });
  }
  return { banks: kept, pending };
}

export interface GeneratedFiles {
  "texts.ts": string;
  "questions.ts": string;
  "keys.ts": string;
  "descriptions.ts": string;
}

const json = (value: unknown): string => JSON.stringify(value, null, 2);

const HEADER = (what: string, serverOnly: boolean): string =>
  `// GENERATED by scripts/unseen-build-bank.ts from resources/english-unseen/bank/*.json. Do not edit by hand:\n` +
  `// change the bank file and run \`npm run unseen-build-bank\`.\n// ${what}\n` +
  // no "server-only" import: the validator reads these files under plain tsx, as it reads the other answer
  // files; only content/answers/index.ts (which is server-only) may import them (constitution Principle I)
  (serverOnly ? `// SERVER ONLY: never import this file from a client component or a public module.\n` : "");

/** Throws with every problem found, so one run lists them all. */
export function buildFiles(banks: BankFile[]): GeneratedFiles {
  const problems: string[] = [];
  const texts = new Map<string, BankFile["texts"][number]>();
  const slugs = new Set<string>();
  const questions: Array<{ q: BankQuestion; paper: BankFile["paper"] }> = [];

  for (const bank of banks) {
    for (const text of bank.texts) {
      if (texts.has(text.id)) problems.push(`duplicate text id ${text.id}`);
      if (!text.hscChecked) problems.push(`text ${text.id}: no hscChecked date (compare it with the NESA HSC papers first)`);
      if (text.body.kind === "image" && !text.description?.trim()) problems.push(`visual text ${text.id}: no description for the marker`);
      texts.set(text.id, text);
    }
    for (const q of bank.questions) {
      if (slugs.has(q.slug)) problems.push(`duplicate question slug ${q.slug}`);
      slugs.add(q.slug);
      if (!texts.has(q.textId) && !bank.texts.some((t) => t.id === q.textId)) problems.push(`${q.slug}: text ${q.textId} not found`);
      for (const s of q.skills) if (!SKILL_IDS.includes(s)) problems.push(`${q.slug}: unknown skill ${s}`);
      questions.push({ q, paper: bank.paper });
    }
  }
  if (problems.length > 0) throw new Error(`bank problems:\n- ${problems.join("\n- ")}`);

  const questionObjects = questions.map(({ q, paper }) => {
    const full: UnseenPaper = { ...paper, qNo: q.qNo };
    const fromLines = q.answerLines !== null && q.answerLines > 0;
    return {
      id: `${UNIT_ID}.${q.slug}`,
      type: "unseen",
      group: "unseen",
      textId: q.textId,
      verb: q.verb,
      prompt: q.prompt,
      ...(q.parts ? { parts: q.parts } : {}),
      maxMarks: q.maxMarks,
      suggestedWords: fromLines ? q.answerLines! * 12 : MEDIAN_WORDS[q.maxMarks],
      suggestedFrom: fromLines ? "lines" : "median",
      paper: full,
      outcome: q.outcome,
      concepts: q.skills.map(skillConceptId),
      source: sourceOf(full),
    };
  });

  const publicTexts = [...texts.values()].map(({ description: _description, ...rest }) => rest);
  const keys = Object.fromEntries(questions.map(({ q }) => [`${UNIT_ID}.${q.slug}`, q.key]));
  const descriptions = Object.fromEntries(
    [...texts.values()].filter((t) => t.description?.trim()).map((t) => [t.id, t.description!.trim()]),
  );

  return {
    "texts.ts":
      HEADER("PUBLIC: every unseen text, once. No answer key (a visual's description is in descriptions.ts).", false) +
      `\nimport type { UnseenText } from "@/lib/types";\n\nexport const texts: UnseenText[] = ${json(publicTexts)};\n`,
    "questions.ts":
      HEADER("PUBLIC: no answer keys. Marking criteria, notes and model answers are in keys.ts (server-only).", false) +
      `\nimport type { Question } from "@/lib/types";\n\nexport const questions: Question[] = ${json(questionObjects)} as Question[];\n`,
    "keys.ts":
      HEADER("SERVER ONLY: the answer key per question (criteria, notes, model answer and their origins).", true) +
      `\nimport type { UnseenKey } from "@/lib/types";\n\nexport const keys: Record<string, Omit<UnseenKey, "visual">> = ${json(keys)};\n`,
    "descriptions.ts":
      HEADER("SERVER ONLY: the marker's written description of each visual text (never sent to a browser).", true) +
      `\nexport const descriptions: Record<string, string> = ${json(descriptions)};\n`,
  };
}
