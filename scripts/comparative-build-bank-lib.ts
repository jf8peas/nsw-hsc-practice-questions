// The pure half of the comparative bank generator (spec 009, research R12, tasks T055): turns the content task's comparative
// bank files (resources/english-unseen/bank/comparative/*.json, gitignored, verbatim paper material) into the comparative
// unit's questions.ts and keys.ts, deterministically. The texts a comparative question shows are the SHARED store's: a
// bank file lists only the texts that are NEW to the store (they join store-texts.ts and, for a visual, descriptions.ts
// through scripts/unseen-build-bank-lib.ts buildFiles(extraTexts)); every other text is pointed at by id. No file or
// network access here; scripts/unseen-build-bank.ts reads and writes.

import { MEDIAN_WORDS } from "../lib/unseen/limits";
import { COMPARATIVE_SKILL_IDS, COMPARATIVE_UNIT_ID, comparativeSkillConceptId, type ComparativeSkillId } from "../lib/unseen/skills";
import { sourceOf } from "../lib/unseen/source";
import type { ComparativeChoice, UnseenPaper, UnseenText } from "../lib/types";
import type { BankFile } from "./unseen-build-bank-lib";

export const COMPARATIVE_UNIT = COMPARATIVE_UNIT_ID;

/** One comparative bank file: one paper, the texts NEW to the shared store, and its multi-text questions. */
export interface ComparativeBankFile {
  paper: Omit<UnseenPaper, "qNo">;
  /** Only texts not already in the store (spec 009 FR-029); a visual carries its marker description (key). */
  texts: Array<UnseenText & { description?: string }>;
  questions: ComparativeBankQuestion[];
}

export interface ComparativeBankQuestion {
  /** The id suffix, e.g. "ab24-q5". */
  slug: string;
  qNo: 1 | 2 | 3 | 4 | 5;
  maxMarks: number;
  verb: string;
  prompt: string;
  parts?: Array<{ label: string; text: string; marks: number }>;
  /** Every answer line the paper gives; null when it cannot be counted (then the median for the mark value applies). */
  answerLines: number | null;
  skills: ComparativeSkillId[];
  outcome: "EAV-12-01" | "EAV-12-02" | "EAV-12-04";
  /** Every text shown, tab order: the fixed texts then the choosable ones. */
  textIds: string[];
  /** null for a fixed pair. */
  choice: ComparativeChoice | null;
  key: {
    criteria: string;
    notes: string;
    model: string;
    modelOrigin: "school" | "drafted";
    criteriaOrigin: "school" | "drafted";
    reviewedOn?: string;
    /** The text ids the model answer uses. */
    pairing: string[];
  };
}

/** Drafted criteria or model answer with no `reviewedOn` date is pending review: the generator keeps it out of the unit. */
export const isComparativePending = (q: ComparativeBankQuestion): boolean =>
  (q.key.modelOrigin === "drafted" || q.key.criteriaOrigin === "drafted") && !q.key.reviewedOn;

/** The bank files without their pending questions, and without new texts only a pending question showed. */
export function withoutPendingComparative(banks: ComparativeBankFile[]): { banks: ComparativeBankFile[]; pending: string[] } {
  const pending: string[] = [];
  const kept: ComparativeBankFile[] = [];
  const shownByKept = new Set<string>();
  const filtered = banks.map((bank) => {
    const questions = bank.questions.filter((q) => {
      if (isComparativePending(q)) pending.push(q.slug);
      return !isComparativePending(q);
    });
    for (const q of questions) for (const id of q.textIds) shownByKept.add(id);
    return { ...bank, questions };
  });
  for (const bank of filtered) {
    if (bank.questions.length === 0) continue;
    kept.push(bank);
  }
  // a text new to the store that no kept comparative question shows is dropped (it may be shown by a pending one only)
  return { banks: kept.map((b) => ({ ...b, texts: b.texts.filter((t) => shownByKept.has(t.id)) })), pending };
}

export interface GeneratedComparativeFiles {
  "questions.ts": string;
  "keys.ts": string;
}

const json = (value: unknown): string => JSON.stringify(value, null, 2);

const HEADER = (what: string, serverOnly: boolean): string =>
  `// GENERATED by scripts/unseen-build-bank.ts from resources/english-unseen/bank/comparative/*.json. Do not edit by hand:\n` +
  `// change the bank file and run \`npm run unseen-build-bank\`.\n// ${what}\n` +
  (serverOnly ? `// SERVER ONLY: never import this file from a client component or a public module.\n` : `// The unit has no questions until the marker check has passed and the bank is released (spec 009 research R7).\n`);

/**
 * Throws with every problem found, so one run lists them all. `knownTextIds` are the ids in the shared store before this
 * run (008's banks); each comparative bank adds its own new texts.
 */
export function buildComparativeFiles(banks: ComparativeBankFile[], knownTextIds: ReadonlySet<string>): GeneratedComparativeFiles {
  const problems: string[] = [];
  const texts = new Set(knownTextIds);
  const slugs = new Set<string>();
  const questions: Array<{ q: ComparativeBankQuestion; paper: ComparativeBankFile["paper"] }> = [];

  for (const bank of banks) {
    for (const text of bank.texts) {
      if (texts.has(text.id)) problems.push(`text ${text.id} is already in the shared store: point at it, do not extract it again`);
      texts.add(text.id);
    }
  }
  for (const bank of banks) {
    for (const q of bank.questions) {
      const where = q.slug;
      if (slugs.has(q.slug)) problems.push(`duplicate question slug ${q.slug}`);
      slugs.add(q.slug);
      for (const id of q.textIds) if (!texts.has(id)) problems.push(`${where}: text ${id} not found in the store or the bank`);
      for (const s of q.skills) if (!(COMPARATIVE_SKILL_IDS as readonly string[]).includes(s)) problems.push(`${where}: unknown skill ${s}`);
      if (q.maxMarks < 3 || q.maxMarks > 8) problems.push(`${where}: marks must be 3 to 8, not ${q.maxMarks}`);
      if (q.choice === null) {
        if (q.textIds.length !== 2) problems.push(`${where}: a fixed pair shows exactly 2 texts`);
      } else {
        const order = [...q.choice.fixed, ...q.choice.from];
        if (order.length !== q.textIds.length || order.some((id, i) => id !== q.textIds[i])) problems.push(`${where}: textIds must be the fixed texts then the choosable texts`);
        if (q.choice.pick < 1 || q.choice.pick > q.choice.from.length) problems.push(`${where}: choice.pick out of range`);
      }
      if (q.key.pairing.some((id) => !q.textIds.includes(id))) problems.push(`${where}: the pairing names a text the question does not show`);
      questions.push({ q, paper: bank.paper });
    }
  }
  if (problems.length > 0) throw new Error(`comparative bank problems:\n- ${problems.join("\n- ")}`);

  const questionObjects = questions.map(({ q, paper }) => {
    const full: UnseenPaper = { ...paper, qNo: q.qNo as UnseenPaper["qNo"] };
    const fromLines = q.answerLines !== null && q.answerLines > 0;
    return {
      id: `${COMPARATIVE_UNIT}.${q.slug}`,
      type: "comparative",
      group: "comparative",
      textIds: q.textIds,
      choice: q.choice,
      verb: q.verb,
      prompt: q.prompt,
      ...(q.parts ? { parts: q.parts } : {}),
      maxMarks: q.maxMarks,
      // no median is guessed for a mark value that has not been counted: validation then refuses the question
      suggestedWords: fromLines ? q.answerLines! * 12 : (MEDIAN_WORDS[q.maxMarks] ?? 0),
      suggestedFrom: fromLines ? "lines" : "median",
      paper: full,
      outcome: q.outcome,
      concepts: q.skills.map(comparativeSkillConceptId),
      source: sourceOf(full),
    };
  });
  const keys = Object.fromEntries(questions.map(({ q }) => [`${COMPARATIVE_UNIT}.${q.slug}`, q.key]));

  return {
    "questions.ts":
      HEADER("PUBLIC: no answer keys. Marking criteria, notes, model answers and pairings are in keys.ts (server-only).", false) +
      `\nimport type { Question } from "@/lib/types";\n\nexport const questions: Question[] = ${json(questionObjects)} as Question[];\n`,
    "keys.ts":
      HEADER("SERVER ONLY: the answer key per question (criteria, notes, model answer, pairing and their origins).", true) +
      `\nimport type { ComparativeKey } from "@/lib/types";\n\nexport const keys: Record<string, Omit<ComparativeKey, "visuals">> = ${json(keys)};\n`,
  };
}

/** The new texts of the comparative banks, as 008's bank files carry them, to join the shared store. */
export function newStoreTexts(banks: ComparativeBankFile[]): BankFile["texts"] {
  return banks.flatMap((b) => b.texts);
}
