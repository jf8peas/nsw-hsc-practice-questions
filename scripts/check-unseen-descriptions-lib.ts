// The pure half of the pre-release description check (spec 008 FR-017, research R3): for one visual
// text, mark every sample answer several times with the real marker, take the majority
// `descriptionAdequate`, and produce the record that description-checks.ts stores. The marker is
// injected, so this is unit-tested with a stub and needs no network or key.

import { createHash } from "node:crypto";

import type { DescriptionCheck } from "../lib/types";

export const REPEATS = 3;

/** sha256 of the description: editing it invalidates a recorded pass. */
export const hashDescription = (description: string): string => createHash("sha256").update(description, "utf8").digest("hex");

/** One marker call on one sample answer: the reply's descriptionAdequate (null when the call failed). */
export type MarkAdequacy = (answer: string) => Promise<boolean | null>;

export interface CheckInput {
  description: string;
  /** The model answer plus the stored pilot answers for the question. */
  samples: string[];
  mark: MarkAdequacy;
  model: string;
  promptVersion: string;
  now?: Date;
}

/**
 * Adequate only when EVERY sample's majority of its REPEATS calls says true (research R3). A failed
 * call counts as not adequate, and no samples at all can never pass. A fail is returned, not hidden.
 */
export async function checkDescription(input: CheckInput): Promise<DescriptionCheck> {
  let allPass = input.samples.length > 0;
  for (const answer of input.samples) {
    let yes = 0;
    for (let i = 0; i < REPEATS; i++) if ((await input.mark(answer)) === true) yes += 1;
    if (yes * 2 <= REPEATS) allPass = false;
  }
  return {
    adequate: allPass,
    checkedAt: (input.now ?? new Date()).toISOString().slice(0, 10),
    promptVersion: input.promptVersion,
    model: input.model,
    samples: input.samples.length,
    descriptionHash: hashDescription(input.description),
  };
}

/** The generated description-checks.ts. Keys sorted so a rerun with no change writes the same file. */
export function renderChecksFile(checks: Record<string, DescriptionCheck>): string {
  const body = Object.keys(checks)
    .sort()
    .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(checks[id])},`)
    .join("\n");
  return `import type { DescriptionCheck } from "@/lib/types";

// SERVER ONLY. GENERATED by scripts/check-unseen-descriptions.ts: the result of the pre-release check
// that each visual text's written description is enough for the marker to mark from (spec 008 FR-017),
// keyed by text id. A visual question without \`adequate: true\` and a matching description hash is
// blocked by \`npm run validate\`. Do not edit by hand.

export const descriptionChecks: Record<string, DescriptionCheck> = {${body ? `\n${body}\n` : ""}};
`;
}
